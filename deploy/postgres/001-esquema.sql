-- Ejecutar conectado a una base nueva. No modifica ni migra la base SQL Server.
BEGIN;
CREATE SCHEMA IF NOT EXISTS dbo;
CREATE TABLE dbo.usuario (
 usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
 correo VARCHAR(254) NOT NULL,
 password_hash VARCHAR(255) NOT NULL CHECK (length(password_hash)>0),
 habilitado BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_usuario_correo ON dbo.usuario(lower(correo));
CREATE TABLE dbo.orientador (
 usuario_id BIGINT PRIMARY KEY REFERENCES dbo.usuario(usuario_id),
 descripcion VARCHAR(1000) NOT NULL DEFAULT '',
 whatsapp VARCHAR(15) CHECK (whatsapp IS NULL OR whatsapp ~ '^[1-9][0-9]{7,14}$'),
 publicar BOOLEAN NOT NULL DEFAULT FALSE,
 actualizado_en TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE dbo.especialidad (
 especialidad_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL UNIQUE CHECK (length(trim(nombre)) > 0)
);
CREATE TABLE dbo.orientadorespecialidad (
 usuario_id BIGINT NOT NULL REFERENCES dbo.orientador(usuario_id),
 especialidad_id INTEGER NOT NULL REFERENCES dbo.especialidad(especialidad_id),
 PRIMARY KEY(usuario_id,especialidad_id)
);
CREATE TABLE dbo.suscripcion (
 suscripcion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES dbo.orientador(usuario_id),
 inicio TIMESTAMPTZ(0) NOT NULL,
 fin TIMESTAMPTZ(0) NOT NULL,
 es_simulada BOOLEAN NOT NULL DEFAULT TRUE CHECK(es_simulada),
 CONSTRAINT ck_suscripcion_mes CHECK (
   fin > inicio AND fin = (((inicio AT TIME ZONE 'America/Lima') + INTERVAL '1 month') AT TIME ZONE 'America/Lima')
 )
);
CREATE INDEX ix_oe_especialidad ON dbo.orientadorespecialidad(especialidad_id,usuario_id);
CREATE INDEX ix_suscripcion_vigencia ON dbo.suscripcion(usuario_id,inicio,fin);
